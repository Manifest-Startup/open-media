/** `open-media completion zsh|bash`: completion scripts generated from the live tool catalog. */
import { flagsFor, Tool } from './schema';

export interface CompletionCommand { name: string; summary: string; flags: { flag: string; values?: string[]; summary?: string; takesValue: boolean }[] }

const globalFlags = ['--json', '--base-url', '--help', '--yes', '--refresh-tools'];

export function toolCompletion(command: string, tool: Tool): CompletionCommand {
  return {
    name: command,
    summary: tool.title ?? tool.description?.split('. ')[0] ?? tool.name,
    flags: [
      ...flagsFor(tool.inputSchema).map((flag) => ({
        flag: `--${flag.flag}`,
        values: flag.enumValues ?? flag.item?.enumValues,
        summary: flag.description,
        takesValue: flag.kind !== 'boolean',
      })),
      { flag: '--input', takesValue: true, summary: 'All arguments as JSON' },
    ],
  };
}

const shellWord = (value: string) => value.replace(/[^A-Za-z0-9_./:@=+-]/g, '');
const zshText = (value: string | undefined) => (value ?? '').replace(/[\n\r]+/g, ' ').replace(/[\[\]:'\\`$"]/g, '').slice(0, 80);

export function bashCompletion(commands: CompletionCommand[]): string {
  const names = commands.map((command) => shellWord(command.name)).join(' ');
  const cases = commands.map((command) => {
    const flags = [...command.flags.map((flag) => shellWord(flag.flag)), ...globalFlags].join(' ');
    const values = command.flags.filter((flag) => flag.values?.length).map((flag) => `        ${shellWord(flag.flag)}) COMPREPLY=($(compgen -W "${flag.values!.map(shellWord).join(' ')}" -- "$cur")); return;;`).join('\n');
    return `    ${shellWord(command.name)})\n      case "$prev" in\n${values ? `${values}\n` : ''}      esac\n      COMPREPLY=($(compgen -W "${flags}" -- "$cur"));;`;
  }).join('\n');
  return `# open-media bash completion (generated by \`open-media completion bash\`).
# Add to ~/.bashrc:  source <(open-media completion bash)
_open_media() {
  local cur="\${COMP_WORDS[COMP_CWORD]}" prev="\${COMP_WORDS[COMP_CWORD-1]}"
  if [ "$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=($(compgen -W "${names}" -- "$cur"))
    return
  fi
  case "\${COMP_WORDS[1]}" in
${cases}
  esac
}
complete -F _open_media open-media
`;
}

export function zshCompletion(commands: CompletionCommand[]): string {
  const described = commands.map((command) => `    '${shellWord(command.name)}:${zshText(command.summary)}'`).join('\n');
  const cases = commands.map((command) => {
    const specs = command.flags.map((flag) => {
      const values = flag.values?.length ? `:value:(${flag.values.map(shellWord).join(' ')})` : flag.takesValue ? ':value:' : '';
      return `'${shellWord(flag.flag)}[${zshText(flag.summary)}]${values}'`;
    });
    return `    ${shellWord(command.name)}) _arguments ${[...specs, ...globalFlags.map((flag) => `'${flag}'`), "'*::arg:'"].join(' ')} ;;`;
  }).join('\n');
  return `#compdef open-media
# open-media zsh completion (generated by \`open-media completion zsh\`).
# Add to ~/.zshrc:  source <(open-media completion zsh)   (after compinit)
_open_media() {
  local -a commands
  commands=(
${described}
  )
  if (( CURRENT == 2 )); then
    _describe 'command' commands
    return
  fi
  local command="\${words[2]}"
  shift words; (( CURRENT-- ))
  case "$command" in
${cases}
  esac
}
compdef _open_media open-media
`;
}
